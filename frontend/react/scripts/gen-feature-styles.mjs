#!/usr/bin/env node
/**
 * ADR 1031 P2 — feature-owned stylesheets.
 *
 * A feature package may own `<feature dir>/styles.css` (first-party
 * `src/features/<id>/` or an adopter's `src/adopter/features/<id>/`). This writes
 * the GITIGNORED `src/styles/features.generated.css`, one `@import` per such file
 * (first-party then adopter, each sorted by directory), which `styles/index.css`
 * imports right after `global.css`. So the ONE stylesheet entry (ADR 0510 §3)
 * picks feature styles up by convention: no upstream file names a package, the
 * CSS stays out of the JS entry chunk, and it is not a lazy `<link>` that would
 * land after `brand.css`.
 *
 * Run at `vite.config.ts` load (dev, build, vitest) — the same pattern as the
 * backend's gen-adopter-features. Writes only when the content changed.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isEntryModule } from '../../../scripts/lib/entry-module.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

/** Every `<feature>/styles.css`, as paths relative to `src/` (`features/x/styles.css`). */
export function featureStylesheets(root = ROOT) {
  const out = [];
  for (const base of ['features', 'adopter/features']) {
    const dir = join(root, 'src', base);
    if (!existsSync(dir)) continue;
    for (const e of readdirSync(dir, { withFileTypes: true }).filter((x) => x.isDirectory()).sort((a, b) => a.name.localeCompare(b.name))) {
      if (existsSync(join(dir, e.name, 'styles.css'))) out.push(`${base}/${e.name}/styles.css`);
    }
  }
  return out;
}

export function generateFeatureStyles(root = ROOT) {
  const files = featureStylesheets(root);
  const body = `/* GENERATED by scripts/gen-feature-styles.mjs (ADR 1031 P2) — do not edit, never committed. */\n${files.map((f) => `@import '../${f}';`).join('\n')}\n`;
  const target = join(root, 'src/styles/features.generated.css');
  if (!existsSync(target) || readFileSync(target, 'utf8') !== body) writeFileSync(target, body);
  return files;
}

if (isEntryModule(import.meta.url)) {
  const files = generateFeatureStyles();
  console.log(`feature stylesheets: ${files.length ? files.join(', ') : '(none)'}`);
}
