#!/usr/bin/env node
// ADR 0873 Verification 2–3 — build the app WITH an offline declaration, for the
// offline e2e lane (playwright.offline.config.ts). No feature declares `offline` on
// main, so the shipped `sw.js` has no engine; this script writes a fixture
// declaration for `kicktodo`, builds into `--out`, and always removes it again.
//
//   node scripts/build-offline-fixture.mjs --out <dir> --variant A|B
//
// `kicktodo` is the fixture because its site-tier routes render without a backend
// (this lane has none) and are lazy, so `/discover` is a dynamically imported screen
// the e2e can reach offline without ever opening it online (D6).
//
// The two variants differ only in VITE_OPENWOP_SITE_URL, which lands in the entry
// chunk, so every chunk that imports it gets a new hash: B is a "deploy" that prunes
// A's chunks, which is what Verification 3 needs. The e2e asserts that difference
// itself rather than trusting this comment.
//
// It writes into src/, so run it in your own worktree: a peer building the same
// checkout during the window would ship the fixture declaration.
import { spawnSync } from 'node:child_process';
import { copyFileSync, existsSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const arg = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};
const out = arg('--out');
const variant = arg('--variant');
if (!out || !['A', 'B'].includes(variant ?? '')) {
  console.error('usage: build-offline-fixture.mjs --out <dir> --variant A|B');
  process.exit(2);
}

const FIXTURE_NAVIGATIONS = ['/guide', '/discover'];
const declaration = resolve(root, 'src/features/kicktodo/offline.ts');
if (existsSync(declaration)) {
  console.error(`build-offline-fixture: ${declaration} already exists; refusing to overwrite a real declaration`);
  process.exit(1);
}

writeFileSync(
  declaration,
  `// GENERATED by scripts/build-offline-fixture.mjs for the offline e2e; never commit.\n` +
    `export const offline = { navigations: ${JSON.stringify(FIXTURE_NAVIGATIONS)} };\n`,
);
let status = 1;
try {
  const outDir = resolve(out);
  const r = spawnSync(
    process.execPath,
    [resolve(root, 'node_modules/vite/bin/vite.js'), 'build', '--outDir', outDir, '--emptyOutDir'],
    {
      cwd: root,
      stdio: 'inherit',
      env: {
        ...process.env,
        VITE_PWA_START_URL: '/guide',
        // kicktodo's closure is ~2,200 kB gzip, over the 1,500 kB default (ADR 0873
        // open question 4). The budget refusal has its own tests; this lane is about
        // what the engine does, so the fixture lifts it.
        OPENWOP_SW_PRECACHE_MAX_KB: '4000',
        VITE_OPENWOP_SITE_URL: `https://offline-fixture-${variant.toLowerCase()}.invalid`,
      },
    },
  );
  status = r.status ?? 1;
  if (status === 0) {
    // What the firebase predeploy (scripts/prepare-hosting-shell.cjs) does to dist/:
    // the shell is served as /app-shell.html and there is no index.html.
    copyFileSync(resolve(outDir, 'index.html'), resolve(outDir, 'app-shell.html'));
    rmSync(resolve(outDir, 'index.html'));
  }
} finally {
  rmSync(declaration, { force: true });
}
process.exit(status);
