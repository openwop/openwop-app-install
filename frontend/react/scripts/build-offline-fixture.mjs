#!/usr/bin/env node
// ADR 0873 Verification 2–3 — build the app WITH an offline declaration, for the
// offline e2e lane (playwright.offline.config.ts). No feature declares `offline` on
// main, so the shipped `sw.js` has no engine; this script writes a small, self-
// contained FIXTURE feature (`offline-fixture`, two lazy site-tier screens and an
// offline declaration) under the ADR 1031 adopter seam, builds into `--out`, and
// always removes it again. Nothing is committed and no registry file is edited:
// the adopter glob composes it, and the service-worker build reads its offline.ts.
//
//   node scripts/build-offline-fixture.mjs --out <dir> --variant A|B
//
// The fixture's screens render without a backend (this lane has none) and are lazy,
// so `/offline-fixture/lazy` is a dynamically imported screen the e2e can reach
// offline without ever opening it online (D6). It was the `kicktodo` package until
// ADR 1031 P2: the lane must not depend on a product that is moving downstream.
//
// The two variants differ only in VITE_OPENWOP_SITE_URL, which lands in the entry
// chunk, so every chunk that imports it gets a new hash: B is a "deploy" that prunes
// A's chunks, which is what Verification 3 needs. The e2e asserts that difference
// itself rather than trusting this comment.
//
// It writes into src/, so run it in your own worktree: a peer building the same
// checkout during the window would ship the fixture declaration.
import { spawnSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const arg = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};
const out = arg('--out');
const variant = arg('--variant');
if (!out || !['A', 'B'].includes(variant ?? '')) {
  console.error('usage: build-offline-fixture.mjs --out <dir> --variant A|B');
  process.exit(2);
}

const START = '/offline-fixture/start';
const LAZY = '/offline-fixture/lazy';
const adopterDir = resolve(root, 'src/adopter');
const adopterExisted = existsSync(adopterDir);
const fixtureDir = resolve(root, 'src/adopter/features/offline-fixture');
if (existsSync(fixtureDir)) {
  console.error(`build-offline-fixture: ${fixtureDir} already exists; refusing to overwrite it`);
  process.exit(1);
}

// The headings are what the e2e asserts (`HEADING` in e2e/serviceWorkerOffline.offline.ts).
const page = (name, heading) =>
  `export function ${name}(): JSX.Element {\n  return <section><h1>${heading}</h1><p>Rendered by the offline e2e fixture.</p></section>;\n}\n`;
mkdirSync(fixtureDir, { recursive: true });
writeFileSync(resolve(fixtureDir, 'StartPage.tsx'), page('StartPage', 'Offline fixture start'));
writeFileSync(resolve(fixtureDir, 'LazyPage.tsx'), page('LazyPage', 'Offline fixture lazy'));
writeFileSync(
  resolve(fixtureDir, 'routes.tsx'),
  `// GENERATED by scripts/build-offline-fixture.mjs for the offline e2e; never commit.\n` +
    `import { lazy } from 'react';\n` +
    `import type { FrontendFeature } from '../../../features/registry.js';\n` +
    `const StartPage = lazy(() => import('./StartPage.js').then((m) => ({ default: m.StartPage })));\n` +
    `const LazyPage = lazy(() => import('./LazyPage.js').then((m) => ({ default: m.LazyPage })));\n` +
    `export const offlineFixtureFeature: FrontendFeature = {\n` +
    `  id: 'offline-fixture',\n` +
    `  routes: [\n` +
    `    { path: '${START}', element: <StartPage />, tier: 'site', auth: 'optional', archetype: 'detail' },\n` +
    `    { path: '${LAZY}', element: <LazyPage />, tier: 'site', auth: 'optional', archetype: 'detail' },\n` +
    `  ],\n` +
    `};\n`,
);
writeFileSync(
  resolve(fixtureDir, 'offline.ts'),
  `// GENERATED by scripts/build-offline-fixture.mjs for the offline e2e; never commit.\n` +
    `export const offline = { navigations: ${JSON.stringify([START, LAZY])} };\n`,
);
let status = 1;
try {
  const outDir = resolve(out);
  const r = spawnSync(
    process.execPath,
    [resolve(root, 'node_modules/vite/bin/vite.js'), 'build', '--outDir', outDir, '--emptyOutDir'],
    {
      cwd: root,
      stdio: 'inherit',
      env: {
        ...process.env,
        VITE_PWA_START_URL: START,
        // The budget refusal has its own tests (ADR 0873 open question 4); this lane is
        // about what the engine does, so the fixture lifts it.
        OPENWOP_SW_PRECACHE_MAX_KB: '4000',
        VITE_OPENWOP_SITE_URL: `https://offline-fixture-${variant.toLowerCase()}.invalid`,
      },
    },
  );
  status = r.status ?? 1;
  if (status === 0) {
    // What the firebase predeploy (scripts/prepare-hosting-shell.cjs) does to dist/:
    // the shell is served as /app-shell.html and there is no index.html.
    copyFileSync(resolve(outDir, 'index.html'), resolve(outDir, 'app-shell.html'));
    rmSync(resolve(outDir, 'index.html'));
  }
} finally {
  rmSync(fixtureDir, { recursive: true, force: true });
  if (!adopterExisted) rmSync(adopterDir, { recursive: true, force: true });
}
process.exit(status);
