const kebab = (camelId) => camelId.replace(/([A-Z])/g, (c) => `-${c.toLowerCase()}`);

/**
 * `{ id, dir, file }` for every feature the registry source composes that has an
 * `offline.ts` beside the module the registry imports. `registrySource` is the
 * text the build actually compiles (a distribution's generated registry when one
 * is set), so an excluded feature contributes no rules.
 */
export function findOfflineDeclarationFiles(registrySource, registryPath) {
  const registryDir = dirname(registryPath);
  const out = [];
  for (const m of registrySource.matchAll(/import \{ (\w+)Feature \} from '([^']+)'/g)) {
    const dir = dirname(resolve(registryDir, m[2]));
    if (dir === registryDir) continue; // a file-based feature has no directory of its own
    const file = join(dir, 'offline.ts');
    if (existsSync(file)) out.push({ id: kebab(m[1]), dir, file });
  }
  return out;
}

/** Strict shape check of one feature's `offline` value. Returns error strings. */
export function checkOfflineShape(id, offline) {
  const errors = [];
  const at = (msg) => errors.push(`${id}: ${msg}`);
  if (!offline || typeof offline !== 'object' || Array.isArray(offline)) return [`${id}: offline must be an object`];
  for (const k of Object.keys(offline)) if (!OFFLINE_KEYS.has(k)) at(`unknown key "${k}"`);
  if (!Array.isArray(offline.navigations) || offline.navigations.length === 0) {
    at('navigations must be a non-empty array');
  } else {
    for (const p of offline.navigations) {
      if (typeof p !== 'string' || !p.startsWith('/') || p === '/' || p.endsWith('/') || /[:*?@{}#\s]/.test(p)) {
        at(`navigation ${JSON.stringify(p)} must be a literal path like "/books" (no "/", params, globs, query or fragment)`);
      }
    }
  }
  if (offline.precache !== undefined) {
    if (!Array.isArray(offline.precache)) at('precache must be an array');
    else for (const p of offline.precache) {
      if (typeof p !== 'string' || !p.startsWith('/') || /[*?@{}#\s]/.test(p) || p.includes('?')) {
        at(`precache ${JSON.stringify(p)} must be an exact path; globs are not allowed`);
      } else if (WORKER_SCRIPTS.has(p) || p === SHELL_URL || p.startsWith('/assets/')) {
        at(`precache ${p} is generated or derived already; do not list it`);
      }
    }
  }
  if (offline.runtime !== undefined) {
    if (!Array.isArray(offline.runtime)) at('runtime must be an array');
    else for (const r of offline.runtime) {
      if (!r || typeof r !== 'object') { at('runtime entries must be objects'); continue; }
      for (const k of Object.keys(r)) if (!RUNTIME_KEYS.has(k)) at(`runtime: unknown key "${k}"`);
      if (typeof r.match !== 'string' || !r.match.startsWith('/')) at(`runtime match ${JSON.stringify(r.match)} must be a same-origin path glob`);
      else if (r.match.startsWith('/assets/') || WORKER_SCRIPTS.has(r.match) || r.match === SHELL_URL) at(`runtime match ${r.match} covers files the worker already owns`);
      if (!STRATEGIES.has(r.strategy)) at(`runtime strategy ${JSON.stringify(r.strategy)} must be "swr" or "network-first"`);
      if (!Number.isInteger(r.maxEntries) || r.maxEntries < 1 || r.maxEntries > MAX_RUNTIME_ENTRIES) {
        at(`runtime maxEntries must be an integer from 1 to ${MAX_RUNTIME_ENTRIES}`);
      }
    }
  }
  if (offline.entitlement !== undefined && !ENTITLEMENTS.has(offline.entitlement)) {
    at(`entitlement ${JSON.stringify(offline.entitlement)} must be "fail-closed" or "last-known"`);
  }
  return errors;
}

/**
 * D4 + D9 checks over the shape-valid declarations. Navigation OWNERSHIP (a
 * path under the feature's own routes) needs the React route modules, so it runs
 * in the vitest lane (`offlineDeclarations.test.ts`), which `npm run ci` gates.
 */
export function checkOfflineTable({ features, neverCache, startUrl }) {
  const errors = [];
  const declared = [];
  for (const { id, offline } of features) {
    for (const p of offline.navigations) {
      declared.push(p);
      if (pathTouchesNeverCache(p, neverCache)) errors.push(`${id}: navigation ${p} intersects a Cloud Run rewrite (D4 never-cache)`);
    }
    for (const p of offline.precache ?? []) {
      if (pathTouchesNeverCache(p, neverCache)) errors.push(`${id}: precache ${p} is a Cloud Run rewrite (D4 never-cache)`);
    }
    for (const r of offline.runtime ?? []) {
      if (globTouchesNeverCache(r.match, neverCache)) errors.push(`${id}: runtime match ${r.match} intersects a Cloud Run rewrite (D4 never-cache)`);
      if (declared.some((p) => new RegExp(firebaseGlobToRegExpSource(r.match)).test(p))) {
        errors.push(`${id}: runtime match ${r.match} covers a declared navigation`);
      }
    }
  }
  const start = new URL(startUrl, 'https://start.invalid').pathname;
  if (neverCache.some(({ source }) => new RegExp(source).test(start))) {
    errors.push(`start_url ${startUrl} is a Cloud Run rewrite, so an installed app cannot launch offline (D9: set VITE_PWA_START_URL)`);
  } else if (!declared.some((p) => start === p || start.startsWith(`${p}/`))) {
    errors.push(`start_url ${startUrl} is not a declared offline navigation (D9: set VITE_PWA_START_URL)`);
  }
  return errors;
}

/**
 * Config-time step of the Vite plugin. Returns `{ features, neverCache }`, with
 * `features` empty when nothing declares (then nothing else is read, so a
 * distribution without a hosting config still builds). Throws one Error listing
 * every problem otherwise.
 *
 * `importModule(file)` loads an `offline.ts` and returns its exports (Vite's
 * `runnerImport` in the build; a plain `import()` in tests).
 */
export async function prepareOfflineBuild({ registrySource, registryPath, importModule, hostingConfigPath, hostingTarget = 'app', startUrl = '/' }) {
  const files = findOfflineDeclarationFiles(registrySource, registryPath);
  if (files.length === 0) return { features: [], neverCache: [] };
  const errors = [];
  const features = [];
  for (const { id, dir, file } of files) {
    const mod = await importModule(file);
    const shape = checkOfflineShape(id, mod.offline);
    errors.push(...shape);
    if (shape.length === 0) features.push({ id, dir, offline: mod.offline });
  }
  let neverCache = [];
  try {
    neverCache = deriveNeverCache(JSON.parse(readFileSync(hostingConfigPath, 'utf8')), hostingTarget);
  } catch (err) {
    errors.push(`cannot read the D4 hosting config ${hostingConfigPath} (target "${hostingTarget}"): ${err.message}. ` +
      'A distribution on its own Firebase project sets VITE_SW_HOSTING_CONFIG and VITE_SW_HOSTING_TARGET.');
  }
  if (errors.length === 0) errors.push(...checkOfflineTable({ features, neverCache, startUrl }));
  if (errors.length > 0) throw new Error(`[sw] ADR 0873 offline table refused:\n  - ${errors.join('\n  - ')}`);
  return { features, neverCache };
}

/** Resolve `VITE_SW_HOSTING_CONFIG` (absolute, or relative to the repo root). */
export function resolveHostingConfigPath(repoRoot, configured) {
  if (!configured) return join(repoRoot, 'firebase.json');
  return isAbsolute(configured) ? configured : resolve(repoRoot, configured);
}

// ---------------------------------------------------------------------------
// D6 — the precache: shell + each feature's chunk graph, versioned and budgeted.
// ---------------------------------------------------------------------------

function sourceBytes(item) {
  if (item.type === 'chunk') return Buffer.from(item.code, 'utf8');
  return typeof item.source === 'string' ? Buffer.from(item.source, 'utf8') : Buffer.from(item.source);
}

/** Static closure (and, when `dynamic`, dynamic closure) of chunk file names,
 *  with each chunk's CSS and assets, never expanding into `stop`. */
function closure(bundle, roots, { dynamic, stop = new Set() }) {
  const seen = new Set();
  const queue = [...roots];
  while (queue.length > 0) {
    const name = queue.pop();
    if (seen.has(name) || stop.has(name)) continue;
    seen.add(name);
    const item = bundle[name];
    if (!item || item.type !== 'chunk') continue;
    for (const dep of item.imports) queue.push(dep);
    if (dynamic) for (const dep of item.dynamicImports) queue.push(dep);
    for (const css of item.viteMetadata?.importedCss ?? []) seen.add(css);
    for (const asset of item.viteMetadata?.importedAssets ?? []) seen.add(asset);
  }
  return seen;
}

/**
 * Compute the precache from the Rollup output bundle.
 *   - shell: `index.html` (deployed as SHELL_URL) + the entry chunks' STATIC graph;
 *   - per feature: every chunk holding a module under the feature's directory,
 *     closed over static AND dynamic imports (a route that `import()`s its
 *     screens must open them offline), minus the shell, plus `precache` extras.
 * Each feature's own part is budgeted in gzip kB.
 *
 * `readPublicFile(path)` returns the bytes of a `public/` file or null.
 * Returns `{ precache, version, sizes, errors }`.
 */
export function computePrecache({ bundle, features, budgetKb = DEFAULT_PRECACHE_MAX_KB, readPublicFile }) {
  const errors = [];
  const html = bundle['index.html'];
  if (!html) errors.push('index.html is not in the bundle, so there is no shell to precache');
  const entries = Object.values(bundle).filter((i) => i.type === 'chunk' && i.isEntry).map((i) => i.fileName);
  const shell = closure(bundle, entries, { dynamic: false });
  const files = new Set(shell);
  const extras = new Map();
  const sizes = [];
  for (const { id, dir, offline } of features) {
    const prefix = dir.endsWith(sep) ? dir : dir + sep;
    const roots = Object.values(bundle)
      .filter((i) => i.type === 'chunk' && !shell.has(i.fileName)
        && i.moduleIds.some((m) => m.split('/').join(sep).startsWith(prefix)))
      .map((i) => i.fileName);
    const own = closure(bundle, roots, { dynamic: true, stop: shell });
    let gzipBytes = 0;
    for (const name of own) {
      files.add(name);
      if (bundle[name]) gzipBytes += gzipSync(sourceBytes(bundle[name])).length;
    }
    for (const p of offline.precache ?? []) {
      const name = p.slice(1);
      const bytes = bundle[name] ? sourceBytes(bundle[name]) : readPublicFile(p);
      if (!bytes) { errors.push(`${id}: precache ${p} is neither build output nor a public/ file`); continue; }
      extras.set(p, bytes);
      gzipBytes += gzipSync(bytes).length;
    }
    const gzipKb = Math.round(gzipBytes / 102.4) / 10;
    sizes.push({ id, gzipKb, chunks: own.size });
    if (gzipKb > budgetKb) {
      errors.push(`${id}: precache is ${gzipKb} kB gzip, over the ${budgetKb} kB budget (OPENWOP_SW_PRECACHE_MAX_KB). ` +
        'Raise it in a reviewed change, or stop the closure reaching shared lazy chunks.');
    }
  }
  const hash = createHash('sha256');
  if (html) hash.update(`index.html\0`).update(sourceBytes(html));
  const sorted = [...files].filter((n) => bundle[n]).sort();
  for (const name of sorted) hash.update(`${name}\0`).update(sourceBytes(bundle[name]));
  for (const [p, bytes] of [...extras].sort(([a], [b]) => a.localeCompare(b))) hash.update(`${p}\0`).update(bytes);
  const precache = [SHELL_URL, ...sorted.map((n) => `/${n}`), ...[...extras.keys()].sort()];
  return { precache: [...new Set(precache)], version: hash.digest('hex').slice(0, 16), sizes, errors };
}

/** The table `generateServiceWorker` injects. */
export function buildOfflineTable({ features, neverCache, precache, version }) {
  return {
    version,
    shellUrl: SHELL_URL,
    precache,
    navigations: [...new Set(features.flatMap((f) => f.offline.navigations))].sort(),
    neverCache: neverCache.map((r) => r.source),
    runtime: features.flatMap((f) => (f.offline.runtime ?? []).map((r) => ({
      match: firebaseGlobToRegExpSource(r.match), strategy: r.strategy, maxEntries: r.maxEntries,
    }))),
  };
}
