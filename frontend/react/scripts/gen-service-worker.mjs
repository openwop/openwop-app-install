/**
 * ADR 0873 — generate the ONE service worker, `/sw.js`, and its offline table.
 *
 * The worker is the push handlers (`sw/push-handlers.js`) plus ONE of:
 *   - `sw/offline-purge.js` when no composed feature declares `offline` (D3, D11):
 *     no `fetch` listener at all, and an activate that deletes every offline cache;
 *   - `sw/offline-engine.js` when the table is non-empty (D4–D7), after a
 *     generated preamble holding the table.
 *
 * Every rule lives here; no feature writes worker code (D1). A feature declares
 * `offline` in a data-only sibling of the module the registry imports,
 * `src/features/<dir>/offline.ts` (`export const offline: FeatureOffline`), and
 * sets the same object on its `FrontendFeature`. The build reads the file, never
 * the React module, and `src/sw/__tests__/offlineDeclarations.test.ts` pins the
 * two together.
 *
 * Used by the `openwop-service-worker` Vite plugin (`vite.config.ts`):
 *   - `prepareOfflineBuild` at config time: load the declarations, derive D4,
 *     run every data check, and decide the `__OPENWOP_SW_OFFLINE__` boot constant;
 *   - `computePrecache` in `generateBundle`: the D6 chunk graphs and the budget;
 *   - `generateServiceWorker` to emit `dist/sw.js` (and to serve `/sw.js` under
 *     `vite dev`, always with the empty table).
 */
import { createHash } from 'node:crypto';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, isAbsolute, join, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

const HERE = dirname(fileURLToPath(import.meta.url));
export const PUSH_HANDLERS_PATH = join(HERE, '..', 'sw', 'push-handlers.js');
export const OFFLINE_ENGINE_PATH = join(HERE, '..', 'sw', 'offline-engine.js');
export const OFFLINE_PURGE_PATH = join(HERE, '..', 'sw', 'offline-purge.js');

/** Every cache the worker owns starts with this. Pinned equal to
 *  `src/sw/offlineCaches.ts` (the page-side sign-out purge, D8). */
export const OFFLINE_CACHE_PREFIX = 'openwop-offline-';
/** D5 — the shell's deployed name. `scripts/prepare-hosting-shell.cjs` renames
 *  `dist/index.html` to this at predeploy; a test pins the two together. */
export const SHELL_URL = '/app-shell.html';
/** D6 — per-feature precache budget, gzip kB (`OPENWOP_SW_PRECACHE_MAX_KB`). */
export const DEFAULT_PRECACHE_MAX_KB = 1500;

const WORKER_SCRIPTS = new Set(['/sw.js', '/sw-push.js']);
const OFFLINE_KEYS = new Set(['navigations', 'precache', 'runtime', 'entitlement']);
const RUNTIME_KEYS = new Set(['match', 'strategy', 'maxEntries']);
const STRATEGIES = new Set(['swr', 'network-first']);
const ENTITLEMENTS = new Set(['fail-closed', 'last-known']);
const MAX_RUNTIME_ENTRIES = 1000;

/**
 * The full text of `/sw.js`. `table` is `null` (or has no navigations) for the
 * empty-table worker; otherwise it is `computePrecache`'s result joined with the
 * declarations (`buildOfflineTable`).
 */
export function generateServiceWorker(table = null) {
  const push = readFileSync(PUSH_HANDLERS_PATH, 'utf8');
  const parts = [
    '/* Generated by scripts/gen-service-worker.mjs (ADR 0873). Do not edit dist/sw.js. */',
    push,
    `const OFFLINE_CACHE_PREFIX = ${JSON.stringify(OFFLINE_CACHE_PREFIX)};`,
  ];
  if (table && table.navigations.length > 0) {
    parts.push(`const OFFLINE = ${JSON.stringify(table, null, 2)};`, readFileSync(OFFLINE_ENGINE_PATH, 'utf8'));
  } else {
    parts.push(readFileSync(OFFLINE_PURGE_PATH, 'utf8'));
  }
  return parts.join('\n');
}

// ---------------------------------------------------------------------------
// D4 — the never-cache set, derived from the hosting config the build deploys to.
// ---------------------------------------------------------------------------

/** A Firebase Hosting glob (`**`, `*`, `?`, `@(a|b)`, `{a,b}`) as an anchored
 *  RegExp source. */
export function firebaseGlobToRegExpSource(glob) {
  let out = '';
  for (let i = 0; i < glob.length; i += 1) {
    const c = glob[i];
    if (c === '*' && glob[i + 1] === '*') { out += '.*'; i += 1; continue; }
    if (c === '*') { out += '[^/]*'; continue; }
    if (c === '?') { out += '[^/]'; continue; }
    if (c === '@' && glob[i + 1] === '(') {
      const end = glob.indexOf(')', i);
      if (end < 0) throw new Error(`unterminated @( in glob ${glob}`);
      out += `(?:${glob.slice(i + 2, end).split('|').map(escapeRegExp).join('|')})`;
      i = end;
      continue;
    }
    if (c === '{') {
      const end = glob.indexOf('}', i);
      if (end < 0) throw new Error(`unterminated { in glob ${glob}`);
      out += `(?:${glob.slice(i + 1, end).split(',').map(escapeRegExp).join('|')})`;
      i = end;
      continue;
    }
    out += escapeRegExp(c);
  }
  return `^${out}$`;
}

function escapeRegExp(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

const isWildcardGlob = (glob) => /[*?@{]/.test(glob);
const literalPrefix = (glob) => glob.split(/[*?@{]/, 1)[0];

/**
 * Every `run` (Cloud Run) rewrite of `target` in a parsed `firebase.json`, as
 * `{ glob, source }`. Throws when the target is absent: a misnamed target would
 * otherwise derive an empty set, which reads as "nothing is dynamic".
 */
export function deriveNeverCache(hostingConfig, target = 'app') {
  const hosting = hostingConfig?.hosting;
  const blocks = Array.isArray(hosting) ? hosting : hosting ? [hosting] : [];
  const block = blocks.length === 1 && !blocks[0].target ? blocks[0] : blocks.find((b) => b.target === target);
  if (!block) throw new Error(`hosting target "${target}" not found in the hosting config`);
  return (block.rewrites ?? [])
    .filter((r) => r.run && typeof r.source === 'string')
    .map((r) => ({ glob: r.source, source: firebaseGlobToRegExpSource(r.source) }));
}

/** True when `path` (a literal path) or anything below it can be a never-cache request. */
function pathTouchesNeverCache(path, neverCache) {
  return neverCache.some(({ glob, source }) => {
    const re = new RegExp(source);
    if (re.test(path) || re.test(`${path}/`)) return true;
    if (!isWildcardGlob(glob)) return glob.startsWith(`${path}/`);
    const lp = literalPrefix(glob);
    return lp !== '' && (lp.startsWith(`${path}/`) || `${path}/`.startsWith(lp));
  });
}

/** True when the requests a runtime glob covers can overlap a never-cache glob. */
function globTouchesNeverCache(glob, neverCache) {
  const own = new RegExp(firebaseGlobToRegExpSource(glob));
  const ownPrefix = literalPrefix(glob);
  return neverCache.some((rule) => {
    if (!isWildcardGlob(rule.glob)) return own.test(rule.glob);
    const lp = literalPrefix(rule.glob);
    return new RegExp(rule.source).test(ownPrefix) || (lp !== '' && (ownPrefix.startsWith(lp) || lp.startsWith(ownPrefix)));
  });
}

