#!/usr/bin/env node
/**
 * Generate `src/client/eventCodemap.generated.ts` — the RENAMED rows of the
 * vendored `schemas/v2/event-codemap.json` as compact `[v1, v2]` pairs.
 *
 * Why generated rather than imported: the full codemap (118 rows with notes)
 * costs ~3.5 kB gzip in the ENTRY chunk and blew `check-bundle-budget`
 * (131.7 kB against a 131 kB ceiling); the 36 pairs cost ~0.7 kB. The
 * vendored file stays the single source of truth: `scripts/sync-schemas.sh`
 * re-runs this after every re-vendor, and
 * `src/client/__tests__/eventVocabulary.test.ts` fails when the generated
 * pairs drift from the file (count parity + round-trip + CORPUS_TAG stamp).
 *
 *   node scripts/gen-event-codemap.mjs           # write
 *   node scripts/gen-event-codemap.mjs --check   # exit 1 when stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, '..', '..', '..');
const codemapPath = join(repoRoot, 'schemas', 'v2', 'event-codemap.json');
const tagPath = join(repoRoot, 'schemas', 'CORPUS_TAG');
const outPath = join(here, '..', 'src', 'client', 'eventCodemap.generated.ts');

const rows = JSON.parse(readFileSync(codemapPath, 'utf8')).rows;
const tag = readFileSync(tagPath, 'utf8').trim();
const pairs = rows.filter((r) => r.v1 !== r.v2).map((r) => [r.v1, r.v2]);
pairs.sort((a, b) => a[0].localeCompare(b[0]));

const body = [
  '// GENERATED by scripts/gen-event-codemap.mjs from schemas/v2/event-codemap.json — do not edit.',
  `// Corpus tag: ${tag}. Re-run after scripts/sync-schemas.sh; eventVocabulary.test.ts fails on drift.`,
  `export const EVENT_CODEMAP_CORPUS_TAG = ${JSON.stringify(tag)};`,
  '/** Renamed event types only: [v1 spelling, v2 spelling]. Identity rows are omitted. */',
  'export const RENAMED_EVENT_TYPES: ReadonlyArray<readonly [string, string]> = [',
  ...pairs.map(([a, b]) => `  [${JSON.stringify(a)}, ${JSON.stringify(b)}],`),
  '];',
  '',
].join('\n');

if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(outPath, 'utf8'); } catch { /* absent counts as stale */ }
  if (current !== body) {
    console.error(`gen-event-codemap: ${outPath} is stale — run node scripts/gen-event-codemap.mjs`);
    process.exit(1);
  }
  console.log(`gen-event-codemap: ok — ${pairs.length} renamed pair(s) current at ${tag}`);
} else {
  writeFileSync(outPath, body);
  console.log(`gen-event-codemap: wrote ${pairs.length} renamed pair(s) at ${tag} → ${outPath}`);
}
