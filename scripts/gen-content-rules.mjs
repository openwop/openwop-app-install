#!/usr/bin/env node
/**
 * ADR 0946 P1 (D3) — write the content-rules tables INTO the packs that read
 * them, never hand-copy them.
 *
 * The ONE source is `backend/typescript/src/host/contentRules/`:
 *   - `channelSpecs.json`  — the dated channel spec table (ad placements,
 *     social post caps, destinations, the copy-default placement per platform);
 *   - `adPolicyRules.json` — the built-in ad text-policy rule list;
 *   - `similarity.ts`      — `findNearDuplicates`, transpiled with esbuild.
 *
 * Packs are standalone `.mjs` (they import only `node:` builtins, so they stay
 * signable and registry-publishable), so each consumer gets a generated
 * `contentRules.generated.mjs` holding exactly what it reads. A pack's copy is
 * pinned to its pack version, which keeps a pure node replay-stable: a table
 * edit reaches a pack only through a regenerate + version bump.
 *
 *   node scripts/gen-content-rules.mjs          # write
 *   node scripts/gen-content-rules.mjs --check  # exit 1 if any copy is stale
 *
 * The derivations here (hard caps, recommendations, schema max, the vendor
 * pack's legacy spec shape) are pinned against
 * the host accessors in `test/adr0946-channel-specs.test.ts`.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isEntryModule } from './lib/entry-module.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const LIB = join(ROOT, 'backend/typescript/src/host/contentRules');
const require = createRequire(join(ROOT, 'backend/typescript/package.json'));
const { transformSync } = require('esbuild');

const SRC = {
  specs: readFileSync(join(LIB, 'channelSpecs.json'), 'utf8'),
  policy: readFileSync(join(LIB, 'adPolicyRules.json'), 'utf8'),
  similarity: readFileSync(join(LIB, 'similarity.ts'), 'utf8'),
};
const specs = JSON.parse(SRC.specs);
const policy = JSON.parse(SRC.policy);

/** Names the host source files a copy was generated from and the sha256 of
 *  their exact bytes, so a copy can be traced to the source it came from. */
const HEADER = (what, sources) => {
  const hash = createHash('sha256');
  for (const k of sources) hash.update(`${k}\0${SRC[k]}\0`);
  const files = sources.map((k) => ({ specs: 'channelSpecs.json', policy: 'adPolicyRules.json', similarity: 'similarity.ts' })[k]).join(', ');
  return `// GENERATED by scripts/gen-content-rules.mjs (ADR 0946 D3). Do not edit: change the
// source, then regenerate. ${what}
// Source: backend/typescript/src/host/contentRules/{${files}}
// Source sha256: ${hash.digest('hex')}\n`;
};
const json = (v) => JSON.stringify(v, null, 2);

function similarityModule() {
  return transformSync(SRC.similarity, { loader: 'ts', format: 'esm', target: 'es2022' }).code;
}

// Only an official `hardMax` blocks or truncates; `recommended` only warns.
function copyDefaults(pick) {
  const byId = new Map(specs.ads.map((r) => [r.channelSpecId, r.text]));
  const out = {};
  for (const [platform, id] of Object.entries(specs.copyDefaults)) {
    const text = byId.get(id);
    if (!text) throw new Error(`channel spec ${id} has no text limits`);
    const caps = {};
    for (const field of ['headline', 'description']) {
      const v = text[field] ? pick(text[field]) : undefined;
      if (v !== undefined) caps[field] = v;
    }
    if (Object.keys(caps).length > 0) out[platform] = caps;
  }
  return out;
}

function postCaps(pick) {
  const out = {};
  for (const r of specs.posts) {
    const v = pick(r.text.content);
    if (v === undefined) continue;
    out[r.platform] = v;
    for (const a of r.aliases ?? []) out[a] = v;
  }
  return out;
}

function schemaMax(caps) {
  const vals = Object.values(caps);
  return {
    headline: Math.max(...vals.map((c) => c.headline ?? 0)),
    description: Math.max(...vals.map((c) => c.description ?? 0)),
    cta: specs.schemaMax.cta,
  };
}

/** The vendor pack's legacy `textLimits` shape, rebuilt from the sourced rows:
 *  `max` is the official hard limit where one is published, else the legacy
 *  (unsourced) value; `recommended` is the sourced one where present. */
function legacySpec(row) {
  const textLimits = {};
  for (const [field, l] of Object.entries(row.text)) {
    const legacy = l.legacy;
    const rec = l.recommended ?? legacy.recommended;
    textLimits[field] = { ...(legacy.min !== undefined ? { min: legacy.min } : {}), max: l.hardMax ?? legacy.max, ...(rec !== undefined ? { recommended: rec } : {}) };
  }
  const { platform, placement, displayName, supportedTypes, ...rest } = row.spec;
  return { platform, placement, displayName, supportedTypes, textLimits, ...rest };
}

const caps = copyDefaults((l) => l.hardMax);
const OUTPUTS = {
  'packs/feature.campaign-channels.nodes/contentRules.generated.mjs':
    HEADER('Channel copy caps + near-duplicate detection.', ['specs', 'similarity'])
    + `export const CHANNEL_SPECS_VERSION = ${json(specs.version)};\n\n`
    + `/** Per-platform ad copy HARD caps (official only): over these, copy is regenerated, then truncated. */\n`
    + `export const PLATFORM_LIMITS = ${json(caps)};\n\n`
    + `/** Per-platform recommended ad copy lengths: over these, QA warns; nothing is truncated. */\n`
    + `export const PLATFORM_RECOMMENDED = ${json(copyDefaults((l) => l.recommended))};\n\n`
    + `/** Social post body HARD caps per platform (and alias), official only. */\n`
    + `export const SOCIAL_LIMITS = ${json(postCaps((l) => l.hardMax))};\n\n`
    + `/** Social post body recommended lengths: QA warns only. */\n`
    + `export const SOCIAL_RECOMMENDED = ${json(postCaps((l) => l.recommended))};\n\n`
    + `/** The widest cap per ad field (schema maxLength; the exact check is per platform). */\n`
    + `export const AD_FIELD_SCHEMA_MAX = ${json(schemaMax(caps))};\n\n`
    + similarityModule(),
  'packs/vendor.myndhyve.ads-platforms/contentRules.generated.mjs':
    HEADER('Ad platform specs from the channel spec table.', ['specs'])
    + `export const CHANNEL_SPECS_VERSION = ${json(specs.version)};\n\n`
    + `export const AD_SPECS = ${json(specs.ads.map(legacySpec))};\n`,
  'packs/vendor.myndhyve.ads-policy/contentRules.generated.mjs':
    HEADER('Built-in ad text-policy rules.', ['policy'])
    + `export const AD_POLICY_RULES_VERSION = ${json(policy.version)};\n\n`
    + `export const AD_POLICY_RULES = ${json(policy.rules)};\n`,
  'packs/vendor.myndhyve.ads-creative-validate/contentRules.generated.mjs':
    HEADER('Built-in ad text-policy rules.', ['policy'])
    + `export const AD_POLICY_RULES_VERSION = ${json(policy.version)};\n\n`
    + `export const AD_POLICY_RULES = ${json(policy.rules)};\n`,
};

/** Exported for the pin test: path → expected content. */
export function expectedOutputs() {
  return OUTPUTS;
}

if (isEntryModule(import.meta.url)) {
  const check = process.argv.includes('--check');
  const stale = [];
  for (const [rel, content] of Object.entries(OUTPUTS)) {
    const abs = join(ROOT, rel);
    const current = existsSync(abs) ? readFileSync(abs, 'utf8') : null;
    if (current === content) continue;
    if (check) stale.push(rel);
    else writeFileSync(abs, content);
  }
  if (check && stale.length > 0) {
    console.error(`✗ gen-content-rules: stale generated copies — run node scripts/gen-content-rules.mjs\n  ${stale.join('\n  ')}`);
    process.exit(1);
  }
  console.log(check ? `✓ gen-content-rules: ${Object.keys(OUTPUTS).length} generated copies current` : `✓ gen-content-rules: wrote ${Object.keys(OUTPUTS).length} generated copies`);
}
