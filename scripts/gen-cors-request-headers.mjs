#!/usr/bin/env node
/**
 * DERIVE the CORS preflight's spec half from the pinned OpenAPI, never hand-write it.
 *
 * `openwop.requirement.headers.cors-preflight-admits` (openwop#1763, suite 2.45.0):
 * a host that grants an origin in preflight MUST admit the operation's method and
 * every request header the OpenAPI declares for that operation, plus
 * `Authorization` and `Content-Type`. The hand list in `middleware/cors.ts` was
 * derived from what the SDK build SENDS (#4204), not from what the spec DECLARES,
 * and missed two: `If-None-Match` (getCapabilities, the run snapshot) and
 * `OpenWOP-Force-Engine-Version` (createRun).
 *
 * Reads every `in: header` parameter (path- and operation-level, `$ref`s
 * resolved) from BOTH served majors in the pinned `@openwop/spec-artifacts`:
 * `api/openapi.yaml` (v1, still served until its EOS) and `api/v2/openapi.yaml`.
 * Writes `backend/typescript/src/middleware/corsRequestHeaders.generated.ts`.
 *
 *   node scripts/gen-cors-request-headers.mjs           # regenerate
 *   node scripts/gen-cors-request-headers.mjs --check   # fail if stale
 *
 * `test/cors-preflight-admits-openapi.test.ts` re-derives the same set and fails
 * on drift, so a spec addition reds a test on the pin bump, not a certify cut.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isEntryModule } from './lib/entry-module.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const BACKEND = join(ROOT, 'backend/typescript');
const OUT = join(BACKEND, 'src/middleware/corsRequestHeaders.generated.ts');
const require = createRequire(join(BACKEND, 'package.json'));
const { parse } = require('yaml');
const ARTIFACTS = dirname(require.resolve('@openwop/spec-artifacts/package.json'));
// TODO(2.45.0 pin): switch the source to `spec/v2/path-manifest.json`'s per-operation
// `requestHeaders`; at 2.44.5 the manifest does not carry them, so openapi.yaml is it.
// v1 is served until its EOS (2026-12-04); at the v1 cut, drop its spec here and
// the set shrinks to v2's naturally.
const SPECS = ['api/openapi.yaml', 'api/v2/openapi.yaml'];
const METHODS = ['get', 'put', 'post', 'delete', 'patch', 'head', 'options', 'trace'];

/** Every header parameter an OpenAPI document declares on any operation. */
export function declaredRequestHeaders(doc) {
  const deref = (p) => (p && p.$ref
    ? p.$ref.slice(2).split('/').reduce((o, k) => o[k.replace(/~1/g, '/').replace(/~0/g, '~')], doc)
    : p);
  const out = new Set();
  for (const item of Object.values(doc.paths ?? {})) {
    for (const m of METHODS) {
      if (!item[m]) continue;
      for (const p of [...(item.parameters ?? []), ...(item[m].parameters ?? [])].map(deref)) {
        if (p?.in === 'header') out.add(p.name);
      }
    }
  }
  return out;
}

export function deriveSpecHeaders() {
  const all = new Set();
  for (const rel of SPECS) {
    for (const h of declaredRequestHeaders(parse(readFileSync(join(ARTIFACTS, rel), 'utf8')))) all.add(h);
  }
  return [...all].sort((a, b) => a.localeCompare(b));
}

function render(headers) {
  const version = JSON.parse(readFileSync(join(ARTIFACTS, 'package.json'), 'utf8')).version;
  return `// GENERATED by scripts/gen-cors-request-headers.mjs from @openwop/spec-artifacts@${version}
// (${SPECS.join(', ')}). Do not edit: re-run the script after a pin bump.

/** Every request header the served OpenAPI documents declare on any operation. */
export const SPEC_REQUEST_HEADERS: readonly string[] = [
${headers.map((h) => `  '${h}',`).join('\n')}
];
`;
}

if (isEntryModule(import.meta.url)) {
  const next = render(deriveSpecHeaders());
  if (process.argv.includes('--check')) {
    let cur = '';
    try { cur = readFileSync(OUT, 'utf8'); } catch { /* absent ⇒ stale */ }
    if (cur !== next) {
      console.error(`✗ ${OUT} is stale: run node scripts/gen-cors-request-headers.mjs`);
      process.exit(1);
    }
    console.log('✓ cors request headers: generated list matches the pinned OpenAPI');
  } else {
    writeFileSync(OUT, next);
    console.log(`wrote ${OUT}`);
  }
}
