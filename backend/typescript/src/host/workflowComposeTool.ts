/**
 * Agent workflow composition — the TWO lanes over one shared pipeline
 * (ADR 0369 §6 + ADR 0473):
 *
 *  - `openwop:workflows.propose` (ADR 0473 — the DEFAULT lane): compose a
 *    bespoke definition, register it as a TRANSIENT draft (catalog-hidden,
 *    `generatedBy: agent:<id>`, builder-editable at /builder/<id>), and HOLD it
 *    on a `composed-workflow` PendingApproval. NOTHING runs until a human
 *    claims — this tool takes no `StartRunDeps`, so there is structurally no
 *    code path from propose to execution.
 *  - `openwop:workflows.compose-and-run` (ADR 0369 §6 — the AUTONOMOUS lane,
 *    superseded as the default by ADR 0473): compose, register, and run
 *    immediately. For explicitly-granted headless agents where a human is not
 *    in the loop by design. Still zero-granted by default.
 *
 * The shared safety argument — there is NO special path:
 *  - the candidate validates against the workflow-definition schema BEFORE
 *    anything is stored (invalid ⇒ tool error, nothing registered);
 *  - capability-gated node types are refused with the SAME rule as
 *    `POST /v1/runs` (`capabilityGatedTypeIdRefusal` — exported from the runs
 *    route so the two gates can never drift);
 *  - execution (immediate or approved) rides the shared `startWorkflowRun`
 *    recipe (replay/fork/observability inherited unchanged); approval gates,
 *    governance, and budgets all apply because it IS an ordinary run;
 *  - promotion to a SAVED workflow stays a USER act (the ADR 0369 §5 verb,
 *    gated on a successful run) — neither lane can mint catalog entries.
 *
 * Approval integrity (ADR 0473): the proposal pins `definitionHash` (SHA-256
 * over the canonical sorted-key JSON). The decide handler re-verifies the hash
 * AFTER its CAS — a builder edit racing the claim reopens the approval instead
 * of running an unreviewed definition (approve-what-you-see, server-enforced).
 *
 * Both tools register at the CORE level via `registerFeatureAgentTool` and are
 * granted per-agent through pack manifests / the ADR 0104 allowlist overrides
 * (default-deny) — never hard-wired to a named agent.
 *
 * Abuse bound (ADR 0369 OQ4): a per-tenant cap on LIVE transient definitions
 * generated by agents (`OPENWOP_AGENT_TRANSIENT_WORKFLOWS_MAX`, default 25) —
 * a runaway agent must not flood the registry/ownership/approval stores.
 */

