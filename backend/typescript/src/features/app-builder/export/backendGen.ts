/** Emit the backend bundle — [] when the design declares no operations (the
 *  openapi.json rule: no dead scaffolding). */
export function generateBackend(state: Record<string, unknown>): BackendFile[] {
  const ops = cleanOps(state);
  if (!ops.length) return [];
  const models = cleanModels(state);
  const files: BackendFile[] = [
    {
      path: 'backend/package.json',
      content: JSON.stringify({
        name: 'generated-backend', private: true, type: 'module',
        scripts: { start: 'tsx src/index.ts' },
        dependencies: Object.fromEntries(PINNED_DEPS),
        devDependencies: { tsx: '4.19.2', typescript: '5.7.2' },
      }, null, 2) + '\n',
    },
    { path: 'backend/src/db/schema.ts', content: emitSchema(models) },
    { path: 'backend/drizzle/0000_init.sql', content: emitMigration(models) },
    { path: 'backend/src/routes.ts', content: emitRoutes(ops, models) },
    ...STATIC_FILES,
    { path: 'backend/sbom.cdx.json', content: emitSbom() },
    ...ops.map((op) => ({ path: `backend/test/fixtures/${op.id}.json`, content: emitFixture(op) })),
  ];
  return files;
}
