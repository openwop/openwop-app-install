/**
 * Production Intelligence store (ADR 0172) — the org-scoped Vendor Directory +
 * the generated ProductionPlan record. Completes the MyndHyve "Production
 * Intelligence (CS-010)" port that ADR 0005 began (Team Profiles only).
 *
 * BOUNDARIES (the boundaries audit, ADR 0172 § Context):
 *  - The `Vendor` entity is the ONE net-new store here. External-org identity a
 *    vendor may map to lives in CRM (`Company`) — a vendor OPTIONALLY references a
 *    `companyId`; it does not re-model the company.
 *  - Team capability data is NOT owned here — it stays in Profiles (ADR 0005);
 *    the context builder reads `profilesService.listProfiles`.
 *  - The `ProductionPlan` is generated by a workflow run (the
 *    `feature.production.nodes.plan-generate` node) and additionally projected as
 *    a run-output artifact (ADR 0055/0083); this record is the durable
 *    source-of-truth for the plan's lifecycle status.
 *
 * Every record carries tenantId + orgId and every accessor verifies BOTH (CTI-1
 * IDOR guard — the CRM `crmEntitiesService` pattern). A vendor field confers NO
 * authority (RFC 0087 §B, the ADR 0005 invariant): quality/contract/capabilities
 * are descriptive and never widen a scope.
 *
 * @see docs/adr/0172-production-intelligence-vendor-directory.md
 */

